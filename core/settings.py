# Resilient DNS resolution for Neon PostgreSQL on networks with incomplete IPv6 routing
_orig_getaddrinfo = socket.getaddrinfo

def _resilient_neon_getaddrinfo(host, port, family=0, type=0, proto=0, flags=0):
    try:
        res = _orig_getaddrinfo(host, port, family, type, proto, flags)
        if family == 0:
            ipv4_res = [r for r in res if r[0] == socket.AF_INET]
            if ipv4_res:
                return ipv4_res
        return res
    except socket.gaierror:
        if host and 'neon.tech' in host:
            return [(socket.AF_INET, socket.SOCK_STREAM, 6, '', ('52.14.39.200', port or 5432))]
        raise

socket.getaddrinfo = _resilient_neon_getaddrinfo

